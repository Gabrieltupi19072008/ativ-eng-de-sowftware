-- Esquema completo para PostgreSQL (Supabase ou contêiner local).
-- Junta os scripts antigos do SQL Server (01_schema ... 05_senha_favoritos, que ficam na pasta sql/ só como histórico).
-- Pode ser executado mais de uma vez: tudo só é criado se ainda não existir.
-- Depois rode: python seed.py (só em ambiente de teste; em produção não se roda o seed).
--
-- Datas: a API grava horário de Brasília (TZ=America/Sao_Paulo), então os padrões do banco usam o mesmo fuso
-- para que "data_pedido" e "data_expiracao" não fiquem 3 horas diferentes.

BEGIN;

-------- 1. Clientes, artistas e endereços
CREATE TABLE IF NOT EXISTS cliente (
	id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nome VARCHAR(120) NOT NULL,
	email VARCHAR(160) NOT NULL UNIQUE,
	senha_hash VARCHAR(255) NOT NULL,
	telefone VARCHAR(30),
	biografia TEXT,
	data_cadastro TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'America/Sao_Paulo'),
	ativo CHAR(1) NOT NULL DEFAULT 'S',
	papel VARCHAR(10) NOT NULL DEFAULT 'COMPRADOR',
	status_artista VARCHAR(20) NOT NULL DEFAULT 'NAO_APLICAVEL',
	cpf CHAR(11),
	cidade VARCHAR(80),
	estado CHAR(2),
	estilo_artistico VARCHAR(80),
	observacao_revisao VARCHAR(500),
	id_revisor INTEGER,
	data_revisao TIMESTAMP,
	data_nascimento DATE,
	CONSTRAINT ck_cliente_ativo CHECK (ativo IN ('S', 'N')),
	CONSTRAINT ck_cliente_papel CHECK (papel IN ('COMPRADOR', 'ARTISTA', 'ADMIN')),
	CONSTRAINT ck_cliente_status_artista CHECK (status_artista IN ('NAO_APLICAVEL', 'PENDENTE', 'APROVADO', 'REJEITADO')),
	CONSTRAINT fk_cliente_revisor FOREIGN KEY (id_revisor) REFERENCES cliente (id_cliente)
);

-- No SQL Server o e-mail ignorava maiúsculas; aqui garantimos o mesmo (a API já grava em minúsculas)
CREATE UNIQUE INDEX IF NOT EXISTS ux_cliente_email_lower ON cliente (lower(email));
-- CPF único, mas só entre quem informou (contas de teste ficam sem CPF)
CREATE UNIQUE INDEX IF NOT EXISTS ux_cliente_cpf ON cliente (cpf) WHERE cpf IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_cliente_artista_status ON cliente (papel, status_artista);

CREATE TABLE IF NOT EXISTS endereco (
	id_endereco INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_cliente INTEGER NOT NULL,
	tipo VARCHAR(20) NOT NULL,
	logradouro VARCHAR(150) NOT NULL,
	numero VARCHAR(20) NOT NULL,
	complemento VARCHAR(100),
	bairro VARCHAR(80) NOT NULL,
	cidade VARCHAR(80) NOT NULL,
	estado CHAR(2) NOT NULL,
	cep VARCHAR(10) NOT NULL,
	-- ativo = 'N' esconde o endereço da conta, mas os pedidos antigos continuam apontando para ele
	ativo CHAR(1) NOT NULL DEFAULT 'S',
	CONSTRAINT fk_endereco_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente),
	CONSTRAINT ck_endereco_tipo CHECK (tipo IN ('ENTREGA', 'COBRANCA')),
	CONSTRAINT ck_endereco_ativo CHECK (ativo IN ('S', 'N'))
);
CREATE INDEX IF NOT EXISTS idx_endereco_cliente ON endereco (id_cliente);

-------- 2. Catálogo de artes e estoque
CREATE TABLE IF NOT EXISTS categoria (
	id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nome VARCHAR(80) NOT NULL UNIQUE,
	descricao VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS produto (
	id_produto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_artista INTEGER NOT NULL,
	nome VARCHAR(150) NOT NULL,
	descricao TEXT,
	sku VARCHAR(60) NOT NULL UNIQUE,
	preco NUMERIC(12, 2) NOT NULL,
	url_imagem VARCHAR(255) NOT NULL,
	ativo CHAR(1) NOT NULL DEFAULT 'S',
	data_cadastro TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'America/Sao_Paulo'),
	ano SMALLINT,
	largura_cm NUMERIC(8, 2),
	altura_cm NUMERIC(8, 2),
	status VARCHAR(10) NOT NULL DEFAULT 'PUBLICADA',
	CONSTRAINT fk_produto_artista FOREIGN KEY (id_artista) REFERENCES cliente (id_cliente),
	CONSTRAINT ck_produto_preco CHECK (preco >= 0),
	CONSTRAINT ck_produto_ativo CHECK (ativo IN ('S', 'N')),
	CONSTRAINT ck_produto_status CHECK (status IN ('PUBLICADA', 'RASCUNHO'))
);

CREATE TABLE IF NOT EXISTS produto_categoria (
	id_produto INTEGER NOT NULL,
	id_categoria INTEGER NOT NULL,
	PRIMARY KEY (id_produto, id_categoria),
	CONSTRAINT fk_produto_categoria_produto FOREIGN KEY (id_produto) REFERENCES produto (id_produto),
	CONSTRAINT fk_produto_categoria_categoria FOREIGN KEY (id_categoria) REFERENCES categoria (id_categoria)
);

-- O CHECK (quantidade >= 0) impede vender além do que existe mesmo se houver falha no código.
CREATE TABLE IF NOT EXISTS estoque (
	id_produto INTEGER PRIMARY KEY,
	quantidade INTEGER NOT NULL DEFAULT 1,
	quantidade_minima INTEGER NOT NULL DEFAULT 0,
	CONSTRAINT fk_estoque_produto FOREIGN KEY (id_produto) REFERENCES produto (id_produto),
	CONSTRAINT ck_estoque_quantidade CHECK (quantidade >= 0),
	CONSTRAINT ck_estoque_minima CHECK (quantidade_minima >= 0)
);

-- Fotos da obra e portfólio do artista
CREATE TABLE IF NOT EXISTS produto_imagem (
	id_imagem INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_produto INTEGER NOT NULL,
	url VARCHAR(255) NOT NULL,
	ordem SMALLINT NOT NULL DEFAULT 0,
	CONSTRAINT fk_produto_imagem_produto FOREIGN KEY (id_produto) REFERENCES produto (id_produto)
);
CREATE INDEX IF NOT EXISTS idx_produto_imagem_produto ON produto_imagem (id_produto);

CREATE TABLE IF NOT EXISTS portfolio_imagem (
	id_imagem INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_cliente INTEGER NOT NULL,
	url VARCHAR(255) NOT NULL,
	ordem SMALLINT NOT NULL DEFAULT 0,
	CONSTRAINT fk_portfolio_imagem_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente)
);
CREATE INDEX IF NOT EXISTS idx_portfolio_imagem_cliente ON portfolio_imagem (id_cliente);

-- Categorias = técnicas usadas nos filtros da loja
INSERT INTO categoria (nome, descricao) VALUES
	('Óleo', 'Pintura a óleo'),
	('Aquarela', 'Pintura em aquarela'),
	('Acrílica', 'Pintura em tinta acrílica'),
	('Pastel', 'Pastel seco ou oleoso'),
	('Arte Digital', 'Criação e impressão digital'),
	('Técnica Mista', 'Combinação de técnicas')
ON CONFLICT (nome) DO NOTHING;

-------- 3. Venda
CREATE TABLE IF NOT EXISTS pedido (
	id_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_cliente INTEGER NOT NULL,
	id_endereco_entrega INTEGER NOT NULL,
	data_pedido TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'America/Sao_Paulo'),
	status VARCHAR(20) NOT NULL DEFAULT 'AGUARDANDO',
	valor_frete NUMERIC(12, 2) NOT NULL DEFAULT 0,
	-- ENVIO é o único tipo em uso por enquanto; RETIRADA (mesma cidade) fica previsto para quando o frete for implementado
	tipo_entrega VARCHAR(10) NOT NULL DEFAULT 'ENVIO',
	-- prazo para pagar: depois dele o pedido é cancelado e a obra volta à vitrine
	data_expiracao TIMESTAMP,
	CONSTRAINT fk_pedido_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente),
	CONSTRAINT fk_pedido_endereco FOREIGN KEY (id_endereco_entrega) REFERENCES endereco (id_endereco),
	CONSTRAINT ck_pedido_status CHECK (status IN ('AGUARDANDO', 'PAGO', 'ENVIADO', 'ENTREGUE', 'CANCELADO')),
	CONSTRAINT ck_pedido_frete CHECK (valor_frete >= 0),
	CONSTRAINT ck_pedido_tipo_entrega CHECK (tipo_entrega IN ('ENVIO', 'RETIRADA'))
);
CREATE INDEX IF NOT EXISTS idx_pedido_cliente ON pedido (id_cliente);
CREATE INDEX IF NOT EXISTS idx_pedido_status ON pedido (status);
CREATE INDEX IF NOT EXISTS idx_pedido_status_expiracao ON pedido (status, data_expiracao);

CREATE TABLE IF NOT EXISTS item_pedido (
	id_pedido INTEGER NOT NULL,
	id_produto INTEGER NOT NULL,
	quantidade INTEGER NOT NULL,
	preco_unitario NUMERIC(12, 2) NOT NULL,
	PRIMARY KEY (id_pedido, id_produto),
	CONSTRAINT fk_item_pedido_pedido FOREIGN KEY (id_pedido) REFERENCES pedido (id_pedido),
	CONSTRAINT fk_item_pedido_produto FOREIGN KEY (id_produto) REFERENCES produto (id_produto),
	CONSTRAINT ck_item_quantidade CHECK (quantidade > 0),
	CONSTRAINT ck_item_preco CHECK (preco_unitario >= 0)
);
CREATE INDEX IF NOT EXISTS idx_item_pedido_produto ON item_pedido (id_produto);

-------- 4. Pagamento e entrega
CREATE TABLE IF NOT EXISTS pagamento (
	id_pagamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_pedido INTEGER NOT NULL UNIQUE,
	forma VARCHAR(20) NOT NULL,
	status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
	valor NUMERIC(12, 2) NOT NULL,
	data_pagamento TIMESTAMP,
	CONSTRAINT fk_pagamento_pedido FOREIGN KEY (id_pedido) REFERENCES pedido (id_pedido),
	CONSTRAINT ck_pagamento_forma CHECK (forma IN ('PIX', 'CARTAO', 'BOLETO')),
	CONSTRAINT ck_pagamento_status CHECK (status IN ('PENDENTE', 'APROVADO', 'RECUSADO', 'ESTORNADO')),
	CONSTRAINT ck_pagamento_valor CHECK (valor >= 0)
);

CREATE TABLE IF NOT EXISTS entrega (
	id_entrega INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_pedido INTEGER NOT NULL UNIQUE,
	codigo_rastreio VARCHAR(60) UNIQUE,
	transportadora VARCHAR(100),
	data_envio DATE,
	data_entrega DATE,
	CONSTRAINT fk_entrega_pedido FOREIGN KEY (id_pedido) REFERENCES pedido (id_pedido),
	CONSTRAINT ck_entrega_datas CHECK (data_entrega IS NULL OR data_envio IS NULL OR data_entrega >= data_envio)
);

-------- 5. Favoritos e recuperação de senha
CREATE TABLE IF NOT EXISTS favorito (
	id_cliente INTEGER NOT NULL,
	id_produto INTEGER NOT NULL,
	data_criacao TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'America/Sao_Paulo'),
	CONSTRAINT pk_favorito PRIMARY KEY (id_cliente, id_produto),
	CONSTRAINT fk_favorito_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente),
	CONSTRAINT fk_favorito_produto FOREIGN KEY (id_produto) REFERENCES produto (id_produto)
);

-- Links de "esqueci minha senha". Guardamos só o hash do código (SHA-256): quem lê o banco não consegue usar o link.
CREATE TABLE IF NOT EXISTS redefinicao_senha (
	id_redefinicao INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id_cliente INTEGER NOT NULL,
	token_hash CHAR(64) NOT NULL UNIQUE,
	data_expiracao TIMESTAMP NOT NULL,
	usado CHAR(1) NOT NULL DEFAULT 'N',
	CONSTRAINT ck_redefinicao_usado CHECK (usado IN ('S', 'N')),
	CONSTRAINT fk_redefinicao_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente)
);

COMMIT;
